"""Задача 1. Тональность отзывов покупателей

Две готовые модели с Hugging Face определяют, какой отзыв: позитивный, нейтральный или негативный
Данные - 30 отзывов о магазинах, написанных вручную, по 10 каждого класса

Запуск:  python text_sentiment.py
"""

import time

from sklearn.metrics import classification_report
from transformers import pipeline

MODELS = [
    "seara/rubert-tiny2-russian-sentiment",     # маленькая модель, 29 млн параметров
    "blanchefort/rubert-base-cased-sentiment",  # большая модель, 178 млн параметров
]

# Отзыв и правильный ответ
REVIEWS = [
    ("Отличный магазин, вежливые продавцы и большой выбор.", "positive"),
    ("Заказ привезли на день раньше, всё целое. Спасибо!", "positive"),
    ("Очень понравился ассортимент, цены ниже, чем у конкурентов.", "positive"),
    ("Консультант помог подобрать размер, буду заказывать ещё.", "positive"),
    ("Быстрая доставка и аккуратная упаковка, рекомендую.", "positive"),
    ("Качество куртки отличное, полностью соответствует описанию.", "positive"),
    ("Удобное приложение, оформила заказ за пару минут.", "positive"),
    ("Вернули деньги за брак без лишних вопросов, приятно удивлена.", "positive"),
    ("Лучший магазин электроники в нашем районе.", "positive"),
    ("Кроссовки сели идеально, очень довольна покупкой.", "positive"),

    ("Магазин работает с девяти утра до девяти вечера.", "neutral"),
    ("Купила чайник, пока пользуюсь всего два дня.", "neutral"),
    ("Обычный магазин, ничего особенного.", "neutral"),
    ("Доставка заняла пять дней, как и было указано.", "neutral"),
    ("Пункт выдачи находится на первом этаже торгового центра.", "neutral"),
    ("Цены как везде, ассортимент стандартный.", "neutral"),
    ("Оплатить можно картой или наличными.", "neutral"),
    ("Размеры соответствуют таблице на сайте.", "neutral"),
    ("Товар забрал сам, курьерской доставкой не пользовался.", "neutral"),
    ("Есть отдел с бытовой химией и отдел с продуктами.", "neutral"),

    ("Продавец нахамил, больше сюда не приду.", "negative"),
    ("Заказ потеряли, деньги возвращали целый месяц.", "negative"),
    ("Привезли разбитую тарелку, курьер отказался оформлять возврат.", "negative"),
    ("Цена на кассе не совпала с ценником, обманывают покупателей.", "negative"),
    ("Ужасное качество, футболка порвалась после первой стирки.", "negative"),
    ("Долго стояла в очереди, работала только одна касса.", "negative"),
    ("Купила просроченный йогурт, никому не советую.", "negative"),
    ("Поддержка не отвечает уже неделю.", "negative"),
    ("Доставку переносили три раза, так и не дождалась.", "negative"),
    ("В зале грязно, на полках пыль.", "negative"),
]

texts = [text for text, label in REVIEWS]
answers = [label for text, label in REVIEWS]

for name in MODELS:
    print(f"\n=== {name} ===")
    model = pipeline("text-classification", model=name)

    model(texts[0])
    start = time.perf_counter()
    results = model(texts)
    seconds = time.perf_counter() - start

    predicted = [result["label"].lower() for result in results]

    print("Ошибки модели (правильно -> ответ модели):")
    for text, answer, guess in zip(texts, answers, predicted):
        if answer != guess:
            print(f"  {answer} -> {guess}: {text}")

    print(classification_report(answers, predicted, digits=2, zero_division=0))
    print(f"Время: {seconds / len(texts) * 1000:.0f} мс на отзыв")
